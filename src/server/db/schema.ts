/** Site ownership transfers. Ownership changes only when the recipient accepts. */
export const siteOwnershipTransfers = pgTable(
  "site_ownership_transfers",
  {
    id: id(),
    siteId: text("site_id")
      .notNull()
      .references(() => sites.id, { onDelete: "cascade" }),
    /** Null once that account is deleted; the transfer history stays with the site. */
    fromUserId: text("from_user_id").references(() => users.id, { onDelete: "set null" }),
    recipientEmail: text("recipient_email").notNull(),
    recipientUserId: text("recipient_user_id").references(() => users.id, {
      onDelete: "set null",
    }),
    status: transferStatus("status").notNull().default("pending"),
    /** Whether the previous owner stays on as Admin after acceptance. */
    previousOwnerRetainsAdmin: boolean("previous_owner_retains_admin").notNull().default(true),
    /** Hash of the acceptance token, used to look it up. */
    tokenHash: text("token_hash").notNull(),
    /** The token, encrypted, so the owner can copy the link again (it isn't emailed yet). */
    tokenEncrypted: text("token_encrypted"),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    respondedAt: timestamp("responded_at", { withTimezone: true }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    index("site_ownership_transfers_site_id_idx").on(t.siteId),
    // At most one pending transfer per site prevents conflicting transfers.
    uniqueIndex("site_ownership_transfers_one_pending")
      .on(t.siteId)
      .where(sql`${t.status} = 'pending'`),
  ],
);

