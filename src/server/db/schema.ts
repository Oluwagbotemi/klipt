/** Applied when a page leaves a field empty. */
export interface SiteSeoDefaults {
  /** e.g. "%s | Northwind Journal"; %s is the page's SEO title. */
  titleTemplate?: string;
  /** Media library image used for social sharing when a page has none. */
  ogImageId?: string;
}

export const siteRole = pgEnum("site_role", ["owner", "admin", "editor", "author", "viewer"]);
export const sitePublishState = pgEnum("site_publish_state", ["live", "not_published"]);

export const sites = pgTable(
  "sites",
  {
    id: id(),
    name: text("name").notNull(),
    /** Primary domain, lower-cased, once connected. Verification is a separate step. */
    domain: text("domain"),
    language: text("language").notNull().default("en"),
    timezone: text("timezone").notNull().default("UTC"),
    publishState: sitePublishState("publish_state").notNull().default("not_published"),
    /** Site-wide switch: false asks search engines not to index anything (e.g. a staging site). */
    allowIndexing: boolean("allow_indexing").notNull().default(true),
    /** Site-wide SEO defaults (see SiteSeoDefaults). */
    seoDefaults: jsonb("seo_defaults").$type<SiteSeoDefaults>().notNull().default({}),
    /** Address on the customer's website that shows drafts (see src/server/previews.ts). */
    previewUrl: text("preview_url"),
    /** Public key the customer's website sends Core Web Vitals with (src/server/performance.ts). */
    vitalsKey: text("vitals_key"),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
    archivedAt: timestamp("archived_at", { withTimezone: true }),
  },
  (t) => [
    uniqueIndex("sites_domain_unique")
      .on(t.domain)
      .where(sql`${t.domain} is not null`),
    uniqueIndex("sites_vitals_key_unique")
      .on(t.vitalsKey)
      .where(sql`${t.vitalsKey} is not null`),
  ],
);

export const siteMembers = pgTable(
  "site_members",
  {
    siteId: text("site_id")
      .notNull()
      .references(() => sites.id, { onDelete: "cascade" }),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    role: siteRole("role").notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    primaryKey({ columns: [t.siteId, t.userId] }),
    index("site_members_user_id_idx").on(t.userId),
    // Exactly one primary owner per site is enforced by the database.
    uniqueIndex("site_members_one_owner")
      .on(t.siteId)
      .where(sql`${t.role} = 'owner'`),
  ],
);

