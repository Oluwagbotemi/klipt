/** A field definition inside a content model. Validated with zod at write time. */
export interface ContentFieldDefinition {
  key: string;
  label: string;
  type:
    | "text"
    | "long_text"
    | "rich_text"
    | "number"
    | "date"
    | "boolean"
    | "select"
    | "media"
    | "reference";
  required: boolean;
  helpText?: string;
  options?: string[];
  referenceModelKeys?: string[];
}

export const contentModels = pgTable(
  "content_models",
  {
    id: id(),
    siteId: text("site_id")
      .notNull()
      .references(() => sites.id, { onDelete: "cascade" }),
    /** Stable API identifier, e.g. "page", "post", "product". */
    key: text("key").notNull(),
    name: text("name").notNull(),
    description: text("description"),
    fields: jsonb("fields").$type<ContentFieldDefinition[]>().notNull().default([]),
    /** Optional schema.org type the model maps to, e.g. "Article". */
    schemaType: text("schema_type"),
    /** Built-in models (Page, Post) cannot be deleted. */
    isSystem: boolean("is_system").notNull().default(false),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [uniqueIndex("content_models_site_key_unique").on(t.siteId, t.key)],
);

